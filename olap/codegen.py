"""Generate a standalone, query-specialized Python program from a validated Phi query.

The generated file depends only on psycopg. Every expression is rendered from the
validated AST by ``expr.to_python`` (literals via repr, names as dict keys), so the
query text is never pasted into the program as code.
"""

from __future__ import annotations

from .engine import equality_keys
from .expr import to_python, walk, RowAttr, GroupAttr
from .spec import PhiQuery

_RUNTIME = '''
def _and(a, b):
    left = a()
    if left is False:
        return False
    right = b()
    if right is False:
        return False
    return None if left is None or right is None else True


def _or(a, b):
    left = a()
    if left is True:
        return True
    right = b()
    if right is True:
        return True
    return None if left is None or right is None else False


def _not(v):
    return None if v is None else not v


def _neg(v):
    return None if v is None else -v


def _cmp(op, a, b):
    if a is None or b is None:
        return None
    if op == "=":
        return a == b
    if op == "<>":
        return a != b
    if op == "<":
        return a < b
    if op == "<=":
        return a <= b
    if op == ">":
        return a > b
    return a >= b


def _ar(op, a, b):
    if a is None or b is None:
        return None
    if op == "+":
        return a + b
    if op == "-":
        return a - b
    if op == "*":
        return a * b
    return None if b == 0 else a / b


def _k(v):
    return int(v) if isinstance(v, float) and v.is_integer() else v


def _scan(conn, cols, table):
    from psycopg import sql
    from psycopg.rows import dict_row
    stmt = sql.SQL("select {} from {}").format(
        sql.SQL(", ").join(sql.Identifier(c) for c in cols), sql.Identifier(table))
    with conn.cursor(name="mf_scan", row_factory=dict_row) as cur:
        cur.itersize = 5000
        cur.execute(stmt)
        for row in cur:
            yield {k: (float(x) if type(x).__name__ == "Decimal" else x) for k, x in row.items()}
'''


def generate(query: PhiQuery) -> str:
    v = query.group_by
    needed = set(v) | {a.attr for a in query.aggregates}
    for node in list(query.sigma.values()) + [query.where]:
        if node is not None:
            needed |= {x.name for x in walk(node) if isinstance(x, (RowAttr, GroupAttr))}
    cols = sorted(needed)
    where = f"if {to_python(query.where, 'r', 'r')} is not True:\n                continue" if query.where else ""

    lines: list[str] = []
    w = lines.append
    w('"""Generated by adhoc-olap-engine. Do not edit; regenerate from the Phi query instead.')
    w("")
    for src_line in query.source.strip().splitlines():
        w("    " + src_line.replace('"""', "'''"))
    w('"""')
    w("import json, os, sys")
    w("import psycopg")
    w(_RUNTIME)
    w("")
    w("def run(conn):")
    w(f"    cols = {cols!r}")
    w(f"    table = {query.table!r}")
    w("    def rows():")
    w("        for r in _scan(conn, cols, table):")
    if where:
        w(f"            {where}")
    w("            yield r")
    w("")
    w("    # Scan 0: build the mf-structure, one entry per distinct grouping-attribute value.")
    w("    mf = {}")
    w("    for r in rows():")
    w(f"        key = ({', '.join(f'r[{a!r}]' for a in v)},)")
    w("        if key not in mf:")
    w(f"            mf[key] = {{{', '.join(f'{a!r}: r[{a!r}]' for a in v)}}}")
    w("    entries = list(mf.values())")

    max_level = max(query.levels.values()) if query.levels else 0
    for level in range(1, max_level + 1):
        gvs = query.gvs_at_level(level)
        w("")
        w(f"    # Scan {level}: grouping variable(s) {gvs}")
        for gv in gvs:
            attrs = sorted({a.attr for a in query.aggregates_for(gv)})
            w(f"    acc{gv} = [{{'n': {{a: 0 for a in {attrs!r}}}, 's': {{}}, 'lo': {{}}, 'hi': {{}}}} for _ in entries]")
            if gv == 0:
                w(f"    idx0 = {{}}")
                w("    for i, g in enumerate(entries):")
                w(f"        idx0.setdefault(({', '.join(f'_k(g[{a!r}])' for a in v)},), []).append(i)")
                continue
            keys = equality_keys(query.sigma[gv], gv)
            if keys:
                w(f"    idx{gv} = {{}}")
                w("    for i, g in enumerate(entries):")
                w(f"        k = ({', '.join('_k(' + to_python(e) + ')' for _, e in keys)},)")
                w("        if None not in k:")
                w(f"            idx{gv}.setdefault(k, []).append(i)")
        w("    for r in rows():")
        for gv in gvs:
            attrs = sorted({a.attr for a in query.aggregates_for(gv)})
            if gv == 0:
                w(f"        cands = idx0.get(({', '.join(f'_k(r[{a!r}])' for a in v)},), ())")
                cond = None
            else:
                keys = equality_keys(query.sigma[gv], gv)
                if keys:
                    w(f"        cands = idx{gv}.get(({', '.join(f'_k(r[{n!r}])' for n, _ in keys)},), ())")
                else:
                    w("        cands = range(len(entries))")
                cond = to_python(query.sigma[gv])
            w("        for i in cands:")
            w("            g = entries[i]")
            if cond:
                w(f"            if {cond} is not True:")
                w("                continue")
            w(f"            a = acc{gv}[i]")
            w(f"            for col in {attrs!r}:")
            w("                x = r[col]")
            w("                if x is None:")
            w("                    continue")
            w("                a['n'][col] += 1")
            w("                if isinstance(x, (int, float)):")
            w("                    a['s'][col] = a['s'].get(col, 0) + x")
            w("                if col not in a['lo'] or x < a['lo'][col]:")
            w("                    a['lo'][col] = x")
            w("                if col not in a['hi'] or x > a['hi'][col]:")
            w("                    a['hi'][col] = x")
        for gv in gvs:
            w("    for i, g in enumerate(entries):")
            w(f"        a = acc{gv}[i]")
            for agg in query.aggregates_for(gv):
                col = agg.attr
                expr = {
                    "count": f"a['n'][{col!r}]",
                    "sum": f"(a['s'][{col!r}] if a['n'][{col!r}] else None)",
                    "avg": f"(a['s'][{col!r}] / a['n'][{col!r}] if a['n'][{col!r}] else None)",
                    "min": f"a['lo'].get({col!r})",
                    "max": f"a['hi'].get({col!r})",
                }[agg.func]
                w(f"        g[{agg.key!r}] = {expr}")

    w("")
    w("    out = []")
    w("    for g in entries:")
    if query.having is not None:
        w(f"        if {to_python(query.having)} is not True:")
        w("            continue")
    w(f"        out.append({{{', '.join(f'{c!r}: g[{c!r}]' for c in query.select)}}})")
    sort_cols = [a for a in v if a in query.select]
    w(f"    out.sort(key=lambda r: tuple((r[c] is None, r[c]) for c in {sort_cols!r}))")
    w("    return out")
    w("")
    w("")
    w('if __name__ == "__main__":')
    w('    dsn = os.environ.get("OLAP_DSN") or (sys.argv[1] if len(sys.argv) > 1 else "")')
    w("    with psycopg.connect(dsn) as conn:")
    w("        with conn.transaction():")
    w("            result = run(conn)")
    w("    json.dump(result, sys.stdout, indent=2, default=str)")
    w('    print()')
    return "\n".join(lines) + "\n"
